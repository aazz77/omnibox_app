//! 编译期内嵌音乐 SDK 的 JS 资产（music-sdk.js + 2 个 preload + polyfill）。
//! 只用标准库，不引入 build-dependency，保证 cargo build --locked 在
//! aarch64-unknown-linux-musl / Windows 上无需额外下载 crate。
//! 运行时不读磁盘，JS 资产直接以 &str 常量编进二进制。
use std::{env, fs, path::Path};

fn main() {
    let manifest = env::var("CARGO_MANIFEST_DIR").unwrap();
    let js_dir = Path::new(&manifest).join("assets").join("js");
    let out = Path::new(&env::var("OUT_DIR").unwrap()).join("embedded_music_js.rs");

    println!("cargo:rerun-if-changed=assets/js");
    assert!(js_dir.is_dir(), "缺少资产目录: assets/js");

    let mut entries: Vec<_> = fs::read_dir(&js_dir)
        .unwrap_or_else(|e| panic!("无法读取 assets/js: {}", e))
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().and_then(|x| x.to_str()) == Some("js"))
        .collect();
    entries.sort();

    let mut code = String::from("// @generated by build.rs —— 请勿手工编辑\n");
    code.push_str("pub static MUSIC_JS: &[(&str, &str)] = &[\n");
    for p in entries {
        let name = p.file_name().unwrap().to_string_lossy().into_owned();
        assert!(!name.contains('"'), "资产名含非法字符");
        let abs = p.to_string_lossy().replace('\\', "/");
        code.push_str(&format!("    (\"{name}\", include_str!(\"{abs}\")),\n"));
    }
    code.push_str("];\n");
    fs::write(&out, code).expect("写 embedded_music_js.rs 失败");
}
